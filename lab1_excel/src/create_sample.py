"""
生成示例 sales_raw.xlsx，包含正常数据与脏数据，用于测试报表脚本。
"""

import pandas as pd


data = [
    # 正常数据
    ['2024-01-05', '张三', '产品A', 10, 50.0, '华东'],
    ['2024-01-08', '李四', '产品B', 5, 120.0, '华北'],
    ['2024-01-12', '张三', '产品A', 8, 50.0, '华东'],
    ['2024-01-15', '王五', '产品C', 3, 200.0, '华南'],
    ['2024-01-20', '李四', '产品B', 2, 120.0, '华北'],
    ['2024-02-03', '张三', '产品A', 6, 50.0, '华东'],
    ['2024-02-10', '王五', '产品C', 4, 200.0, '华南'],
    ['2024-02-18', '李四', '产品D', 7, 80.0, '华北'],

    # 脏数据：关键字段缺失
    ['2024-01-06', None, '产品A', 2, 50.0, '华东'],
    ['2024-01-09', '张三', None, 3, 50.0, '华东'],

    # 脏数据：数量 <= 0
    ['2024-01-11', '张三', '产品A', -5, 50.0, '华东'],
    ['2024-01-13', '李四', '产品B', 0, 120.0, '华北'],

    # 脏数据：重复行
    ['2024-01-05', '张三', '产品A', 10, 50.0, '华东'],
]


df = pd.DataFrame(data, columns=['日期', '销售员', '产品', '数量', '单价', '地区'])
df.to_excel('sales_raw.xlsx', index=False, engine='openpyxl')
print("已生成 sales_raw.xlsx")
